"""Builds the "bugs" scene for the marketing home page.

An uptime pulse runs across the panel. A red paper bug walks onto it, the
line drops flat and red, a ping marks the spot, and the pulse comes back
once the bug is gone. Timing lives in bug-scene.component.scss.

    python3 scripts/bug-art/build.py

writes projects/marketing/src/app/shared/bug-scene/bug-scene.component.html.
"""

from pathlib import Path

W, H = 520, 112
BASE = 60  # baseline y
BEAT = 130  # px per heartbeat; the line scrolls one beat per cycle
STOP = 260  # where the bug stops on the line


# The paper bug sticker (public/assets/home/bug.webp), head up, 197x200.
BUG_W, BUG_H = 38, 38.6


def pulse():
    """Enough beats to cover the panel plus one, so scrolling a beat loops cleanly."""
    d = [f"M0 {BASE}"]
    for k in range(W // BEAT + 2):
        x = k * BEAT
        d.append(
            f"L{x + 40} {BASE} q5 -7 10 0 L{x + 60} {BASE} l5 8 l8 -58 l8 70 l5 -20 "
            f"L{x + 98} {BASE} q7 -10 14 0 L{x + BEAT} {BASE}"
        )
    return " ".join(d)


def bug():
    return f"""<g class="bug">
    <g class="bug__body">
      <image class="bug__paper" href="/assets/home/bug.webp" x="{-BUG_W / 2}" y="{-BUG_H / 2}" width="{BUG_W}" height="{BUG_H}" />
    </g>
  </g>"""


def scene():
    parts = [
        f"""<defs>
    <linearGradient id="pulse-fade">
      <stop offset="0" stop-color="#fff" stop-opacity="0" />
      <stop offset="0.15" stop-color="#fff" />
      <stop offset="0.85" stop-color="#fff" />
      <stop offset="1" stop-color="#fff" stop-opacity="0" />
    </linearGradient>
    <mask id="pulse-mask"><rect width="{W}" height="{H}" fill="url(#pulse-fade)" /></mask>
  </defs>""",
        f"""<g mask="url(#pulse-mask)">
    <g class="pulse"><path class="pulse__line" d="{pulse()}" /></g>
    <line class="flat" x1="0" y1="{BASE}" x2="{W}" y2="{BASE}" />
  </g>""",
        f'<circle class="ping" cx="{STOP}" cy="{BASE}" r="16" />',
        bug(),
    ]
    body = "\n  ".join(parts)
    label = "A paper bug walks onto an uptime pulse and the line goes flat until it is gone"
    return f'<svg class="art" viewBox="0 0 {W} {H}" role="img" aria-label="{label}">\n  {body}\n</svg>\n'


def main():
    d = Path(__file__).resolve().parents[2] / "projects/marketing/src/app/shared/bug-scene"
    html = "<!-- Generated by scripts/bug-art/build.py; edit that, not this. -->\n" + scene()
    (d / "bug-scene.component.html").write_text(html)
    (d / "_bug-walk.scss").unlink(missing_ok=True)
    print(d, len(html), "bytes")


if __name__ == "__main__":
    main()
